// Writes src/car/liveryMask.js from tools/liverymask.html (run after changing a car body).
import { chromium } from 'playwright';
import { spawn } from 'node:child_process';
import { writeFileSync } from 'node:fs';
const port = 8000 + Math.floor(Math.random() * 900);
const server = spawn(process.execPath, ['tools/serve.mjs'], { env: { ...process.env, PORT: String(port) }, stdio: 'ignore' });
await new Promise((r) => setTimeout(r, 400));
const b = await chromium.launch();
try {
  const p = await b.newPage();
  p.on('pageerror', (e) => console.log('ERR', e.message));
  await p.goto(`http://localhost:${port}/tools/liverymask.html`);
  await p.waitForFunction(() => document.title === 'done', null, { timeout: 300000 });
  const m = await p.evaluate(() => window.__mask);
  writeFileSync('src/car/liveryMask.js', `/*
 * Generated by tools/liverymask.mjs: for each car body, where the livery's side and top projections
 * land on a flat, continuous panel. ${256}x${64} cells over each band (8x8 canvas px), column-major
 * from the nose; a byte per cell, 0 = no usable panel, else 1 + the panel's depth (0..254).
 */
export const MASK_U = 256, MASK_V = 64;
export const MASKS = ${JSON.stringify(m, null, 1)};
`);
  console.log('ok', Object.keys(m));
} finally { await b.close(); server.kill(); }
